    /** Opis kodu po polsku; dla kodów spoza listy – układ, którego kod dotyczy. */
    fun describe(code: String): String {
        val c = code.uppercase()
        known[c]?.let { return it }
        if (c.length < 3) return "Nieznany kod"
        return when (c[0]) {
            'U' -> "Komunikacja między sterownikami"
            'C' -> "Usterka w układzie podwozia"
            'B' -> "Usterka w układzie nadwozia"
            else -> when {
                c[1] == '1' || c[1] == '3' && c[2] < '4' -> "Kod własny producenta – zapytaj asystenta"
                c[2] == '0' || c[2] == '1' -> "Układ paliwa i powietrza"
                c[2] == '2' -> "Układ wtrysku paliwa"
                c[2] == '3' -> "Układ zapłonu lub nierówna praca silnika"
                c[2] == '4' -> "Układ oczyszczania spalin"
                c[2] == '5' -> "Prędkość pojazdu, bieg jałowy, wejścia pomocnicze"
                c[2] == '6' -> "Sterownik silnika i jego wyjścia"
                c[2] in "789" -> "Skrzynia biegów"
                else -> "Usterka układu napędowego"
            }
        }
    }
